/**
 * Load a language file asynchronously.
 * Returns cached dict if already loaded.
 * Falls back to 'en' if the requested language file fails to load.
 */
export const loadLanguage = async (lang) => {
  if (cache[lang]) return cache[lang];
  const importer = langImporters[lang];
  if (!importer) {
    // Unknown language — fall back to en
    return cache['en'] || {};
  }
  try {
    const mod = await importer();
    cache[lang] = mod.default;
    return cache[lang];
  } catch {
    if (lang !== 'en') return loadLanguage('en');
    return {};
  }
};

/**
 * Set the current language.
 * For lazy-loaded languages, triggers async load.
 * Returns a promise that resolves when the language dict is available.
 */
export const setLanguage = async (lang) => {
  currentLang = lang;
  return loadLanguage(lang);
};

/**
 * Translate a key to the current language (synchronous).
 * Falls back: currentLang dict -> 'en' dict -> key itself.
 * For lazy-loaded languages that haven't loaded yet, falls back to English.
 */
export const t = (key, fallback) => {
  const dict = cache[currentLang] || cache['en'] || {};
  return dict[key] || (cache['en'] || {})[key] || fallback || key;
};

/**
 * Get the current language code.
 */
export const getCurrentLang = () => currentLang;

/**
 * Check if a language is loaded in cache.
 */
export const isLanguageLoaded = (lang) => !!cache[lang];

/**
 * Get the TRANSLATIONS object in legacy format { key: { en, ko, ... } }
 * for backward compatibility. Only includes loaded languages.
 * @deprecated Use t() instead
 */
export const getLegacyTranslations = () => {
  const result = {};
  const allKeys = new Set();
  for (const dict of Object.values(cache)) {
    for (const key of Object.keys(dict)) allKeys.add(key);
  }
  for (const key of allKeys) {
    result[key] = {};
    for (const [lang, dict] of Object.entries(cache)) {
      if (dict[key] !== undefined) result[key][lang] = dict[key];
    }
  }
  return result;
};

// Legacy export for backward compatibility
// Consumers that import { TRANSLATIONS } will get a proxy that builds on demand
export const TRANSLATIONS = new Proxy({}, {
  get(_, key) {
    if (typeof key !== 'string') return undefined;
    const entry = {};
    for (const [lang, dict] of Object.entries(cache)) {
      if (dict[key] !== undefined) entry[lang] = dict[key];
    }
    return Object.keys(entry).length > 0 ? entry : undefined;
  },
  has(_, key) {
    if (typeof key !== 'string') return false;
    for (const dict of Object.values(cache)) {
      if (dict[key] !== undefined) return true;
    }
    return false;
  },
  ownKeys() {
    const allKeys = new Set();
    for (const dict of Object.values(cache)) {
      for (const key of Object.keys(dict)) allKeys.add(key);
    }
    return [...allKeys];
  },
  getOwnPropertyDescriptor(_, key) {
    for (const dict of Object.values(cache)) {
      if (dict[key] !== undefined) {
        return { configurable: true, enumerable: true, value: this.get(_, key) };
      }
    }
    return undefined;
  },
});
